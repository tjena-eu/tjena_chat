// Slot lifecycle: free -> assigned -> burned. A burned slot is never handed
// out again, because its ghosts may still be joined to the old owner's rooms
// and Synapse keeps accepting its real as_token until the next restart.
const (
	SlotFree     = "free"
	SlotAssigned = "assigned"
	SlotBurned   = "burned"
)

type Slot struct {
	Name    string `json:"name"`     // e.g. "wa07"
	ASID    string `json:"as_id"`    // registration id, e.g. "tjena-wa07"
	ASToken string `json:"as_token"` // real token known to Synapse; never leaves the gateway
	HSToken string `json:"hs_token"` // real token Synapse uses towards us
	State   string `json:"state"`

	Owner string `json:"owner,omitempty"`
	// Tokens handed to the owner's bridge app. The gateway swaps them for the
	// real ones, so rotating or deleting them revokes the bridge instantly.
	BridgeASToken string    `json:"bridge_as_token,omitempty"`
	BridgeHSToken string    `json:"bridge_hs_token,omitempty"`
	AssignedAt    time.Time `json:"assigned_at,omitzero"`
	BurnedAt      time.Time `json:"burned_at,omitzero"`
	// Set once the registration is known to be loaded by Synapse.
	Active bool `json:"active"`
}

func (s *Slot) BotLocalpart() string     { return s.Name + "bot" }
func (s *Slot) UsernameTemplate() string { return s.Name + "_{{.}}" }

type stateFile struct {
	Slots []*Slot `json:"slots"`
}

type Store struct {
	path string
	mu   sync.Mutex
	st   stateFile
}

func openStore(dataDir string) (*Store, error) {
	if err := os.MkdirAll(dataDir, 0o700); err != nil {
		return nil, err
	}
	s := &Store{path: filepath.Join(dataDir, "state.json")}
	data, err := os.ReadFile(s.path)
	if errors.Is(err, os.ErrNotExist) {
		return s, nil
	} else if err != nil {
		return nil, err
	}
	if err = json.Unmarshal(data, &s.st); err != nil {
		return nil, fmt.Errorf("parse %s: %w", s.path, err)
	}
	return s, nil
}

// saveLocked writes atomically (temp file + rename).
func (s *Store) saveLocked() error {
	data, err := json.MarshalIndent(&s.st, "", "  ")
	if err != nil {
		return err
	}
	tmp := s.path + ".tmp"
	if err = os.WriteFile(tmp, data, 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, s.path)
}

// Update runs fn under the lock and persists the result if fn succeeds.
func (s *Store) Update(fn func(st *stateFile) error) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	backup, _ := json.Marshal(&s.st)
	if err := fn(&s.st); err != nil {
		var restored stateFile
		_ = json.Unmarshal(backup, &restored)
		s.st = restored
		return err
	}
	return s.saveLocked()
}

// View runs fn under the lock without saving.
func (s *Store) View(fn func(st *stateFile)) {
	s.mu.Lock()
	defer s.mu.Unlock()
	fn(&s.st)
}

func randomToken(nBytes int) string {
	b := make([]byte, nBytes)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return base64.RawURLEncoding.EncodeToString(b)
}

func slotName(prefix string, n int) string { return fmt.Sprintf("%s%02d", prefix, n) }

var slotNum = regexp.MustCompile(`(\d+)$`)

func (st *stateFile) maxSlotNumber() int {
	maxN := 0
	for _, s := range st.Slots {
		if m := slotNum.FindStringSubmatch(s.Name); m != nil {
			var n int
			fmt.Sscan(m[1], &n)
			maxN = max(maxN, n)
		}
	}
	return maxN
}

func (st *stateFile) find(name string) *Slot {
	for _, s := range st.Slots {
		if s.Name == name {
			return s
		}
	}
	return nil
}

func (st *stateFile) ownedBy(mxid string) []*Slot {
	var out []*Slot
	for _, s := range st.Slots {
		if s.State == SlotAssigned && s.Owner == mxid {
			out = append(out, s)
		}
	}
	return out
}

func (st *stateFile) firstFree() *Slot {
	for _, s := range st.Slots {
		if s.State == SlotFree && s.Active {
			return s
		}
	}
	return nil
}

// registrationYAML renders the Synapse appservice registration for a slot.
func registrationYAML(cfg *Config, s *Slot) string {
	domain := regexp.QuoteMeta(cfg.ServerName)
	return fmt.Sprintf(`# Personal WhatsApp bridge slot %[1]s. Generated by bridge-gateway; do not edit.
id: %[2]s
url: %[3]s
as_token: %[4]s
hs_token: %[5]s
sender_localpart: %[6]s
rate_limited: false
namespaces:
  users:
    - regex: '^@%[6]s:%[7]s$'
      exclusive: true
    - regex: '^@%[1]s_.*:%[7]s$'
      exclusive: true
  aliases: []
  rooms: []
de.sorunome.msc2409.push_ephemeral: true
receive_ephemeral: true
# End-to-bridge encryption in appservice mode (Synapse does not allow /sync
# for appservice users). Needs experimental_features msc2409_to_device_messages_enabled
# and msc3202_transaction_extensions in homeserver.yaml.
org.matrix.msc3202: true
io.element.msc4190: true
`, s.Name, s.ASID, cfg.InternalURL, s.ASToken, s.HSToken, s.BotLocalpart(), domain)
}

func writeRegistration(cfg *Config, s *Slot) (string, error) {
	if err := os.MkdirAll(cfg.RegistrationDir, 0o755); err != nil {
		return "", err
	}
	p := filepath.Join(cfg.RegistrationDir, s.ASID+".yaml")
	// Synapse runs as a different user in its container, so the file must be
	// readable by it. The directory should only be mounted into Synapse.
	return p, os.WriteFile(p, []byte(registrationYAML(cfg, s)), 0o644)
}

func synapseSnippet(cfg *Config, slots []*Slot) string {
	var b strings.Builder
	b.WriteString("app_service_config_files:\n  # ... keep your existing entries, then add:\n")
	for _, s := range slots {
		fmt.Fprintf(&b, "  - %s/%s.yaml\n", cfg.RegistrationDirInSynapse, s.ASID)
	}
	return b.String()
}
